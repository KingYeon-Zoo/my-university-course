/*
 * ====================================================================
 * 嵌入式系统课程设计 - 系统启动汇编文件
 * ====================================================================
 * 功能：ARM系统启动引导和中断向量表设置
 * 
 * 主要功能：
 * 1. 系统启动初始化（关看门狗、设置栈、初始化硬件）
 * 2. 程序重定位（从Flash复制到SDRAM）
 * 3. 中断向量设置和中断服务程序入口
 * 4. 跳转到main函数开始C程序执行
 * 
 * 启动流程：
 * reset -> 硬件初始化 -> 重定位 -> 清BSS -> 跳转main
 * 
 * 修改指导：
 * - 【不可修改】此文件为系统底层启动代码，任何修改都可能导致系统无法启动
 * - 【不可修改】中断向量表设置是中断系统正常工作的基础
 * - 【不可修改】内存布局和重定位逻辑经过精确设计
 * - 【注意】如需调试，可以在指定位置添加调试代码，但不建议修改现有逻辑
 * ====================================================================
 */

/*
 * ====================================================================
 * 全局符号声明和外部函数引用
 * ====================================================================
 */
.globl _start           // 程序入口点，对外可见
.global asm_timer_irq   // 定时器中断汇编入口，提供给C代码使用
.extern do_irq          // 外部C函数：中断处理函数

/*
 * ====================================================================
 * 系统启动入口点
 * 【不可修改】系统启动的第一条指令，由硬件复位后自动跳转到此处
 * ====================================================================
 */
_start:

reset:
	/*
	 * ================================================================
	 * 步骤1：配置外设基地址
	 * 告诉CPU外设寄存器的地址空间范围，用于内存映射IO访问
	 * ================================================================
	 */
	// 外设地址告诉cpu
    ldr r0, =0x70000000      // 加载外设基地址
    orr r0, r0, #0x13        // 设置地址属性
    mcr p15,0,r0,c15,c2,4    // 写入协处理器寄存器，配置内存映射
    
	/*
	 * ================================================================
	 * 步骤2：关闭看门狗定时器
	 * 防止系统在初始化过程中被看门狗复位
	 * ================================================================
	 */
	// 关看门狗
	ldr r0, =0x7E004000      // 看门狗控制寄存器地址
	mov r1, #0               // 禁用看门狗
	str r1, [r0]             // 写入寄存器
	
	/*
	 * ================================================================
	 * 步骤3：使能向量中断控制器(VIC)
	 * 打开ARM处理器的中断处理能力
	 * ================================================================
	 */
	//Enable VIC
	mrc p15,0,r0,c1,c0,0     // 读取系统控制寄存器
	orr r0,r0,#(1<<24)       // 设置VIC使能位
	mcr p15,0,r0,c1,c0,0     // 写回系统控制寄存器	

	/*
	 * ================================================================
	 * 步骤4：设置系统栈指针
	 * 为C程序运行提供栈空间，栈用于函数调用和局部变量存储
	 * ================================================================
	 */
	// 设置栈
	ldr sp, =8*1024          // 设置栈指针为8KB位置（向下增长）

	/*
	 * ================================================================
	 * 步骤5：调用各个硬件初始化函数
	 * 按顺序初始化时钟、内存、存储和中断系统
	 * 【注意】初始化顺序很重要，不能随意调整
	 * ================================================================
	 */
	// 初始化时钟
	bl clock_init            // 调用时钟初始化函数（在clock.c中定义）

	// 初始化ddr
	bl sdram_init            // 调用SDRAM内存初始化（在sdram.c中定义）

	// 初始化nandflash
	bl nand_init             // 调用NAND Flash存储初始化（在nand.c中定义）

	// 初始化中断
	bl irq_init              // 调用中断系统初始化（在timer.c中定义）
	
	/*
	 * ================================================================
	 * 步骤6：开启全局中断
	 * 清除CPSR寄存器的中断禁止位，允许中断发生
	 * ================================================================
	 */
	// 开中断
	//mov r0, #0x53          // 备用方法：直接设置CPSR值
	//msr CPSR_cxsf, r0      // 备用方法：写入CPSR
	mrs r0,cpsr              // 读取当前CPSR状态
	bic r0,r0,#0x80          // 清除IRQ中断禁止位（bit7）
	msr cpsr_c,r0            // 写回CPSR，开启IRQ中断

	/*
	 * ================================================================
	 * 步骤7：程序重定位
	 * 将程序从启动位置（Flash/NAND）复制到运行位置（SDRAM）
	 * 这是为了提高程序运行速度（SDRAM比Flash快）
	 * ================================================================
	 */
	// 重定位，把程序的代码段、数据段复制到它的链接地址去
	adr r0, _start   		// 当前程序实际运行地址
	ldr r1, =_start  		// 程序链接地址（期望运行的地址）
	ldr r2, =bss_start      // BSS段开始地址
	sub r2, r2, r1          // 计算需要复制的程序大小
	cmp r0,r1               // 比较实际地址和链接地址
	beq clean_bss           // 如果相同，跳过复制直接清BSS
	bl copy2ddr		        // 否则调用复制函数			
	cmp r0, #0              // 检查复制结果
	bne halt                // 复制失败则停机

	/*
	 * ================================================================
	 * 步骤8：清零BSS段
	 * BSS段存放未初始化的全局变量，需要在程序开始前清零
	 * ================================================================
	 */
	// 清BSS，把BSS段对应的内存清零
clean_bss:
	ldr r0, =bss_start      // BSS段开始地址
	ldr r1, =bss_end        // BSS段结束地址
	mov r3, #0              // 清零值
	cmp r0, r1              // 检查BSS段是否为空
	beq on_ddr              // 如果为空，直接跳转
clean_loop:
	str r3, [r0], #4        // 写入0并移动指针
	cmp r0, r1              // 检查是否清零完成
	bne clean_loop          // 继续清零循环

	/*
	 * ================================================================
	 * 步骤9：跳转到C程序main函数
	 * 系统初始化完成，开始执行用户程序
	 * ================================================================
	 */
on_ddr:
	// 跳转
	ldr pc, =main           // 加载main函数地址并跳转

	/*
	 * ================================================================
	 * 中断异常处理入口
	 * 【不可修改】定时器中断的汇编级处理程序
	 * ================================================================
	 */
	// 中断异常
asm_timer_irq:
	.word irq               // 中断向量，指向实际的中断处理代码

/*
 * ====================================================================
 * IRQ中断处理程序
 * 【不可修改】这是ARM标准的中断处理流程
 * ====================================================================
 */

/*
 * 功能：IRQ中断服务程序
 * 
 * 中断处理流程：
 * 1. 保存现场（寄存器状态）
 * 2. 调用C语言中断处理函数
 * 3. 恢复现场并返回
 * 
 * 注意：ARM处理器在进入中断时会自动保存部分状态，
 *       但用户寄存器需要手动保存和恢复
 */
irq:
	/*
	 * ================================================================
	 * 步骤1：保存现场
	 * 将可能被中断处理程序修改的寄存器保存到栈中
	 * ================================================================
	 */
	ldr sp, =0x54000000                    // 设置中断栈指针
	sub lr, lr, #4                         // 调整返回地址（ARM中断返回地址需要-4）
	stmfd sp!, {r0-r12, lr}                // 保存通用寄存器和返回地址到栈

	/*
	 * ================================================================
	 * 步骤2：调用C语言中断处理函数
	 * 跳转到timer.c中的do_irq函数执行具体的中断处理逻辑
	 * ================================================================
	 */
	bl do_irq                              // 调用C语言中断处理函数

	/*
	 * ================================================================
	 * 步骤3：恢复现场并返回
	 * 从栈中恢复寄存器状态，返回到中断前的程序位置
	 * ================================================================
	 */
	ldmfd sp!, {r0-r12, pc}^               // 恢复寄存器并返回（^表示同时恢复CPSR）

/*
 * ====================================================================
 * 系统停机处理
 * 【不可修改】用于处理无法恢复的系统错误
 * ====================================================================
 */

/*
 * 功能：系统停机循环
 * 当系统遇到无法恢复的错误时，进入无限循环防止系统异常运行
 */
halt:
	b halt                                 // 无限循环，停机


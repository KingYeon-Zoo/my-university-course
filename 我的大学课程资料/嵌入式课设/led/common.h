#define __COMMON_H

/*
 * ====================================================================
 * 寄存器访问基础宏定义
 * 【重要】提供统一的寄存器访问方式，简化硬件操作代码
 * ====================================================================
 */

/*
 * 基础寄存器访问宏
 * vi: volatile integer pointer - 声明易失性整数指针
 * 用于访问硬件寄存器，volatile关键字防止编译器优化寄存器访问
 */
#define vi *( volatile unsigned int * ) 

/*
 * ====================================================================
 * 位操作宏定义集合
 * 【可扩展】这些宏简化了常见的位操作，可根据需要添加更多
 * ====================================================================
 */

/*
 * 位清零操作宏
 * 功能：将指定地址的指定位清零（设为0）
 * 参数：addr - 寄存器地址, bit - 位号（0-31）
 * 示例：set_zero(0x7F008800, 5) -> 将地址0x7F008800的第5位清零
 * 应用：常用于关闭某个功能或清除状态位
 */
#define set_zero( addr, bit ) ( (vi addr) &= ( ~ ( 1 << (bit) ) ) )

/*
 * 位置一操作宏  
 * 功能：将指定地址的指定位置1
 * 参数：addr - 寄存器地址, bit - 位号（0-31）
 * 示例：set_one(0x7F008800, 5) -> 将地址0x7F008800的第5位置1
 * 应用：常用于使能某个功能或设置状态位
 */
#define set_one( addr, bit ) ( (vi addr) |= ( 1 << ( bit ) ) )

/*
 * 单位设置操作宏
 * 功能：将指定地址的指定位设置为指定值（0或1）
 * 参数：addr - 寄存器地址, bit - 位号, val - 值（0或1）
 * 示例：set_bit(0x7F008800, 5, 1) -> 将地址0x7F008800的第5位设为1
 * 应用：根据条件动态设置位状态
 */
#define set_bit( addr, bit, val ) ( (vi addr) = (( vi addr)&=(~(1<<(bit))) ) | ( (val)<<(bit) ) )

/*
 * 2位设置操作宏
 * 功能：设置连续2位的值（常用于配置寄存器的功能选择）
 * 参数：addr - 寄存器地址, bit - 起始位号, val - 2位值（0-3）
 * 示例：set_2bit(0x7F008800, 4, 2) -> 将地址0x7F008800的第4-5位设为10
 * 应用：配置GPIO功能选择（输入/输出/特殊功能）
 */
#define set_2bit( addr, bit, val ) ( (vi addr) = (( vi addr)&(~(3<<(bit))) ) | ( (val)<<(bit) ) )

/*
 * N位设置操作宏（通用版本）
 * 功能：设置连续N位的值
 * 参数：addr - 寄存器地址, bit - 起始位号, len - 位数, val - N位值
 * 示例：set_nbit(0x7F008800, 4, 3, 5) -> 将地址0x7F008800的第4-6位设为101
 * 应用：设置多位配置字段，如分频值、模式选择等
 */
#define set_nbit( addr, bit, len,  val ) \
	( (vi addr) = ((( vi addr)&(~(( ((1<<(len))-1) )<<(bit))))  | ( (val)<<(bit) ) ))

/*
 * ====================================================================
 * 位读取操作宏定义
 * 【常用】用于读取和检测寄存器位状态
 * ====================================================================
 */

/*
 * 位状态读取宏
 * 功能：读取指定地址的指定位状态
 * 参数：addr - 寄存器地址, bit - 位号
 * 返回：该位为1时返回非0值，为0时返回0
 * 示例：get_bit(0x7F008834, 0) -> 读取K1按键状态
 * 应用：按键状态检测、中断状态查询等
 */
#define get_bit( addr, bit ) ( (( vi addr ) & ( 1 << (bit) )) > 0  )

/*
 * ====================================================================
 * 寄存器整体操作宏定义
 * 【常用】用于整个寄存器的读写操作
 * ====================================================================
 */

/*
 * 寄存器值读取宏（带参数版本）
 * 功能：读取寄存器值并存储到变量中
 * 参数：addr - 寄存器地址, val - 存储变量
 * 应用：需要对寄存器值进行多次操作时使用
 */
#define get_val( addr, val ) ( (val) = vi addr )

/*
 * 寄存器值直接读取宏
 * 功能：直接返回寄存器的值
 * 参数：addr - 寄存器地址
 * 返回：寄存器的当前值
 * 应用：一次性读取寄存器值用于判断或计算
 */
#define read_val( addr ) ( vi ( addr ) )

/*
 * 寄存器值设置宏
 * 功能：将指定值写入寄存器
 * 参数：addr - 寄存器地址, val - 要写入的值
 * 应用：寄存器初始化、状态设置等
 */
#define set_val( addr, val ) ( (vi addr) = (val) )

/*
 * 寄存器或操作宏
 * 功能：将寄存器当前值与指定值进行或运算
 * 参数：addr - 寄存器地址, val - 或操作值
 * 应用：设置寄存器的特定位而不影响其他位
 */
#define or_val( addr, val ) ( (vi addr) |= (val) ) 


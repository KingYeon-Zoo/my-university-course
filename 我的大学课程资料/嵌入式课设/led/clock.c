/*
 * ====================================================================
 * 嵌入式系统课程设计 - 系统时钟初始化文件
 * ====================================================================
 * 功能：配置ARM处理器（S3C6410）的系统时钟
 * 
 * 时钟系统说明：
 * - APLL：应用处理器锁相环，为CPU核心提供时钟
 * - MPLL：内存锁相环，为AHB和APB总线设备提供时钟  
 * - EPLL：外设锁相环，为UART、IIS、IIC等外设提供时钟
 * 
 * 时钟频率配置：
 * - ARMCLK：532MHz（CPU核心时钟）
 * - HCLKX2：266MHz（高速总线时钟×2）
 * - HCLK：133MHz（高速总线时钟）
 * - PCLK：66.5MHz（外设总线时钟）
 * 
 * 修改指导：
 * - 【不建议修改】此文件为系统关键时钟配置，修改可能导致系统不稳定
 * - 【不建议修改】PLL参数和分频比例经过精确计算，不建议随意调整
 * - 【注意】如需修改定时器精度，建议在timer.c中调整定时器参数而非系统时钟
 * ====================================================================
 */

// 功能:c语言初始化时钟

/*
 * ====================================================================
 * 锁相环锁定时间寄存器定义
 * 【重要】此区域为硬件寄存器地址定义，不可修改！
 * ====================================================================
 */
#define APLL_LOCK (*((volatile unsigned long *)0x7E00F000))  // APLL锁定时间寄存器
#define MPLL_LOCK (*((volatile unsigned long *)0x7E00F004))  // MPLL锁定时间寄存器  
#define EPLL_LOCK (*((volatile unsigned long *)0x7E00F008))  // EPLL锁定时间寄存器

/*
 * 系统控制寄存器
 */
#define OTHERS    (*((volatile unsigned long *)0x7e00f900))  // 其他控制寄存器

/*
 * 时钟分频寄存器
 */
#define CLK_DIV0  (*((volatile unsigned long *)0x7E00F020))  // 时钟分频控制寄存器0

/*
 * ====================================================================
 * 时钟分频比例定义 - 系统时钟频率计算的关键参数
 * 【重要】这些参数决定了整个系统的运行频率，不建议修改！
 * ====================================================================
 */
#define ARM_RATIO    0   // ARMCLK分频比：ARMCLK = DOUTAPLL / (ARM_RATIO + 1) = 532/(0+1) = 532MHz
#define MPLL_RATIO   0   // MPLL分频比：DOUTMPLL = MOUTMPLL / (MPLL_RATIO + 1) = 532/(0+1) = 532MHz
#define HCLKX2_RATIO 1   // HCLKX2分频比：HCLKX2 = HCLKX2IN / (HCLKX2_RATIO + 1) = 532/(1+1) = 266MHz
#define HCLK_RATIO   1   // HCLK分频比：HCLK = HCLKX2 / (HCLK_RATIO + 1) = 266/(1+1) = 133MHz
#define PCLK_RATIO   3   // PCLK分频比：PCLK = HCLKX2 / (PCLK_RATIO + 1) = 266/(3+1) = 66.5MHz

/*
 * ====================================================================
 * 锁相环控制寄存器和配置值定义
 * 【重要】PLL配置值经过精确计算，不建议修改！
 * ====================================================================
 */
#define APLL_CON  (*((volatile unsigned long *)0x7E00F00C))  // APLL控制寄存器
#define APLL_CON_VAL  ((1<<31) | (250 << 16) | (3 << 8) | (1))  // APLL配置值：使能+MDIV=250+PDIV=3+SDIV=1

#define MPLL_CON  (*((volatile unsigned long *)0x7E00F010))  // MPLL控制寄存器  
#define MPLL_CON_VAL  ((1<<31) | (250 << 16) | (3 << 8) | (1))  // MPLL配置值：使能+MDIV=250+PDIV=3+SDIV=1

/*
 * 时钟源选择寄存器
 */
#define CLK_SRC  (*((volatile unsigned long *)0x7E00F01C))  // 时钟源选择寄存器

/*
 * ====================================================================
 * 系统时钟初始化函数
 * 【不建议修改】此函数为系统启动的关键步骤，修改可能导致系统无法正常运行
 * ====================================================================
 */

/*
 * 功能：初始化系统时钟
 * 
 * 初始化流程：
 * 1. 设置PLL锁定时间（等待PLL稳定的时间）
 * 2. 设置为异步模式（CPU时钟和总线时钟可以独立）
 * 3. 配置各级时钟的分频系数
 * 4. 启动PLL进行时钟倍频
 * 5. 选择PLL输出作为系统时钟源
 * 
 * 注意：此函数在系统启动时被start.S调用，在main函数之前执行
 */
void clock_init(void)
{	
	/*
	 * ================================================================
	 * 步骤1：设置各PLL的锁定时间
	 * 锁定时间决定PLL从启动到输出稳定时钟所需的等待时间
	 * 使用默认值0xffff确保PLL有足够时间稳定
	 * ================================================================
	 */
	APLL_LOCK = 0xffff;		// APLL锁定时间，供CPU使用 
	MPLL_LOCK = 0xffff;		// MPLL锁定时间，供AHB(存储/中断/lcd等控制器)/APB(看门狗，定时器，SD等)总线上的设备使用
	EPLL_LOCK = 0xffff;		// EPLL锁定时间，供UART,IIS,IIC使用 

	/*
	 * ================================================================
	 * 步骤2：设置为异步模式(Asynchronous mode)
	 * 异步模式允许CPU时钟和总线时钟独立运行，提高系统性能
	 * ================================================================
	 */
	OTHERS &= ~0xc0;		// 清除同步模式位，设置为异步模式						
	while ((OTHERS & 0xf00) != 0);	// 等待模式切换完成

	/*
	 * ================================================================
	 * 步骤3：设置分频系数
	 * 根据预定义的分频比例配置各级时钟频率
	 * 所有分频比例组合决定了最终的系统时钟频率
	 * ================================================================
	 */
	CLK_DIV0 = (ARM_RATIO) | (MPLL_RATIO << 4) | (HCLK_RATIO << 8) | (HCLKX2_RATIO << 9) | (PCLK_RATIO << 12);

	/*
	 * ================================================================
	 * 步骤4：设置PLL配置，启动时钟倍频
	 * PLL将低频晶振信号倍频为高频系统时钟
	 * APLL和MPLL都配置为相同的倍频参数
	 * ================================================================
	 */
	APLL_CON = APLL_CON_VAL;	// 配置APLL：使能+倍频参数
	MPLL_CON = MPLL_CON_VAL;	// 配置MPLL：使能+倍频参数

	/*
	 * ================================================================
	 * 步骤5：选择PLL输出作为系统时钟源
	 * 完成从晶振时钟到PLL高频时钟的切换
	 * 0x03表示同时选择APLL和MPLL作为时钟源
	 * ================================================================
	 */
	CLK_SRC = 0x03;	// 选择PLL输出作为时钟源

/*
 * ====================================================================
 * 时钟配置总结和影响
 * ====================================================================
 * 
 * 配置完成后的系统时钟频率：
 * - CPU核心频率：532MHz（影响程序执行速度）
 * - 内存访问频率：133MHz（影响数据传输速度）  
 * - 外设总线频率：66.5MHz（影响定时器、UART等外设工作频率）
 * 
 * 对项目的影响：
 * 1. 定时器精度：PCLK=66.5MHz为定时器提供基准时钟
 * 2. 按键响应：系统频率影响按键扫描的实时性
 * 3. LED显示：中断响应速度影响LED显示的流畅性
 * 
 * 注意事项：
 * - 修改时钟配置需要重新计算定时器参数
 * - 过高的时钟频率可能导致功耗增加和系统不稳定
 * - 过低的时钟频率可能影响系统实时性能
 * 
 * 如需调整定时精度，建议：
 * 1. 保持系统时钟配置不变
 * 2. 在timer.c中调整定时器的预分频和分频参数
 * 3. 通过修改定时器计数值来调整具体的定时时间
 * ====================================================================
 */
}


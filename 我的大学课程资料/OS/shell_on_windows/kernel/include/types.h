/*
 * types.h - Shell内核核心数据结构定义文件
 * 
 * 本文件定义了shell内核中使用的所有核心数据结构。
 * 设计遵循Linux内核编码风格和内存效率原则。
 * 
 * 主要包含:
 * - 词法分析器(Lexer)使用的Token类型和结构
 * - 语法分析器(Parser)使用的AST节点类型和结构
 * - 变量表的哈希表实现
 * - 执行上下文结构
 * - 内存池结构
 * - 命令映射结构
 */

#ifndef _SHELL_TYPES_H
#define _SHELL_TYPES_H

#include <stddef.h>  /* 标准定义，包含size_t等 */
#include <stdint.h>  /* 标准整数类型，包含int8_t, int32_t等 */

/*============================================================================
 * 最大限制常量定义
 * 这些常量限制了各种数据结构的最大容量，用于防止缓冲区溢出
 *============================================================================*/
#define MAX_TOKEN_LEN       256   /* 单个Token的最大长度（字符数） */
#define MAX_CMD_ARGS        64    /* 命令最大参数个数 */
#define MAX_VAR_NAME        64    /* 变量名的最大长度 */
#define MAX_VAR_VALUE       1024  /* 变量值的最大长度 */
#define MAX_PATH_LEN        260   /* 文件路径的最大长度（Windows MAX_PATH） */
#define HASH_TABLE_SIZE     128   /* 哈希表桶的数量 */
#define MAX_REDIRECT_FILES  3     /* 最大重定向文件数（stdin, stdout, stderr） */

/*============================================================================
 * Token类型枚举 - 词法分析阶段使用
 * 
 * 词法分析器将输入文本分解成一系列Token，每个Token都有一个类型。
 * 这些类型用于区分不同种类的词法单元。
 *============================================================================*/
typedef enum {
	/* 基础Token类型 */
	TOKEN_WORD,           /* 普通单词或字符串，如命令名、文件名等 */
	TOKEN_NUMBER,         /* 数字字面量，如 123, 456 */
	TOKEN_VARIABLE,       /* 变量引用，如 $var, ${var} */
	TOKEN_ASSIGN,         /* 赋值运算符 (=) */
	TOKEN_SEMICOLON,      /* 命令分隔符 (;) 用于在同一行执行多个命令 */
	TOKEN_PIPE,           /* 管道运算符 (|) 用于连接命令的输出和输入 */
	TOKEN_REDIRECT_IN,    /* 输入重定向 (<) 从文件读取输入 */
	TOKEN_REDIRECT_OUT,   /* 输出重定向 (>) 将输出写入文件（覆盖） */
	TOKEN_REDIRECT_APPEND,/* 追加重定向 (>>) 将输出追加到文件末尾 */
	TOKEN_AND,            /* 逻辑与 (&&) 前一命令成功才执行下一命令 */
	TOKEN_OR,             /* 逻辑或 (||) 前一命令失败才执行下一命令 */
	TOKEN_BACKGROUND,     /* 后台执行 (&) 在后台运行命令 */
	
	/* Shell关键字Token - 用于控制流语句 */
	TOKEN_IF,             /* if 关键字 - 条件判断开始 */
	TOKEN_THEN,           /* then 关键字 - if条件成立时执行 */
	TOKEN_ELSE,           /* else 关键字 - if条件不成立时执行 */
	TOKEN_ELIF,           /* elif 关键字 - else if的缩写 */
	TOKEN_FI,             /* fi 关键字 - if语句结束 */
	TOKEN_WHILE,          /* while 关键字 - while循环开始 */
	TOKEN_DO,             /* do 关键字 - 循环体开始 */
	TOKEN_DONE,           /* done 关键字 - 循环结束 */
	TOKEN_FOR,            /* for 关键字 - for循环开始 */
	TOKEN_IN,             /* in 关键字 - for循环的迭代列表 */
	TOKEN_CASE,           /* case 关键字 - case语句开始 */
	TOKEN_ESAC,           /* esac 关键字 - case语句结束（case的反写） */
	TOKEN_FUNCTION,       /* function 关键字 - 函数定义 */
	
	/* 特殊Token类型 */
	TOKEN_NEWLINE,        /* 换行符 - 用于分隔多行脚本 */
	TOKEN_EOF,            /* 文件结束 - 标记输入结束 */
	TOKEN_ERROR           /* 错误Token - 词法分析出错时使用 */
} token_type_t;

/*============================================================================
 * Token结构体 - 词法单元
 * 
 * 每个Token代表输入文本中的一个词法单元。
 * Token通过next指针连接成链表，便于后续遍历处理。
 *============================================================================*/
struct token {
	token_type_t type;              /* Token的类型 */
	char value[MAX_TOKEN_LEN];      /* Token的字符串值 */
	int line;                       /* Token所在的行号（用于错误报告） */
	int column;                     /* Token所在的列号（用于错误报告） */
	struct token *next;             /* 指向下一个Token的指针（链表结构） */
};

/*============================================================================
 * AST节点类型枚举 - 语法分析阶段使用
 * 
 * 抽象语法树(Abstract Syntax Tree, AST)的节点类型。
 * 每种类型代表一种不同的语法结构。
 *============================================================================*/
typedef enum {
	AST_COMMAND,          /* 简单命令节点 - 如 ls -la */
	AST_PIPELINE,         /* 管道节点 - 如 ls | grep foo | wc -l */
	AST_SEQUENCE,         /* 顺序执行节点 - 多个命令按顺序执行 */
	AST_IF,               /* if语句节点 - 条件分支 */
	AST_WHILE,            /* while循环节点 - 条件循环 */
	AST_FOR,              /* for循环节点 - 遍历循环 */
	AST_CASE,             /* case语句节点 - 模式匹配 */
	AST_ASSIGNMENT,       /* 变量赋值节点 - 如 x=10 */
	AST_REDIRECT          /* I/O重定向节点 - 如 > file.txt */
} ast_node_type_t;

/* 前向声明 - 解决结构体之间的相互引用 */
struct ast_node;
struct redirect_info;

/*============================================================================
 * 命令节点结构体 - 表示单个命令及其参数
 * 
 * 用于存储一个完整的shell命令，包括命令名、参数列表、
 * 重定向信息和后台执行标志。
 *============================================================================*/
struct cmd_node {
	char *name;                           /* 命令名称（如 ls, echo, cat） */
	char *args[MAX_CMD_ARGS];             /* 参数数组（args[0]通常是命令名本身） */
	int argc;                             /* 参数计数（包括命令名） */
	struct redirect_info *redirects;      /* 重定向信息链表 */
	int background;                       /* 后台执行标志（1=后台执行，0=前台执行） */
};

/*============================================================================
 * 管道节点结构体 - 表示通过管道连接的多个命令
 * 
 * 管道将多个命令连接起来，前一个命令的输出作为后一个命令的输入。
 * 例如: ls -la | grep txt | wc -l
 *============================================================================*/
struct pipeline_node {
	struct ast_node **commands;           /* 命令节点数组 */
	int cmd_count;                        /* 管道中的命令数量 */
};

/*============================================================================
 * if语句节点结构体 - 表示条件分支语句
 * 
 * 对应shell语法: if condition; then body; [else body;] fi
 *============================================================================*/
struct if_node {
	struct ast_node *condition;           /* 条件表达式（通常是test命令） */
	struct ast_node *then_body;           /* then分支（条件为真时执行） */
	struct ast_node *else_body;           /* else分支（条件为假时执行，可以为NULL） */
};

/*============================================================================
 * while循环节点结构体 - 表示条件循环语句
 * 
 * 对应shell语法: while condition; do body; done
 * 当条件为真时重复执行循环体。
 *============================================================================*/
struct while_node {
	struct ast_node *condition;           /* 循环条件 */
	struct ast_node *body;                /* 循环体 */
};

/*============================================================================
 * for循环节点结构体 - 表示遍历循环语句
 * 
 * 对应shell语法: for var in word1 word2 ...; do body; done
 * 遍历单词列表，依次将每个单词赋值给循环变量并执行循环体。
 *============================================================================*/
struct for_node {
	char *var_name;                       /* 循环变量名 */
	char **word_list;                     /* 要遍历的单词列表 */
	int word_count;                       /* 单词数量 */
	struct ast_node *body;                /* 循环体 */
};

/*============================================================================
 * case模式结构体 - 表示case语句中的单个模式
 * 
 * case语句可以有多个模式，每个模式匹配成功后执行对应的命令。
 * 模式通过链表连接。
 *============================================================================*/
struct case_pattern {
	char *pattern;                        /* 匹配模式（支持通配符） */
	struct ast_node *body;                /* 匹配成功时执行的命令 */
	struct case_pattern *next;            /* 指向下一个模式的指针 */
};

/*============================================================================
 * case语句节点结构体 - 表示模式匹配语句
 * 
 * 对应shell语法: case $var in pattern1) body;; pattern2) body;; esac
 *============================================================================*/
struct case_node {
	char *var_name;                       /* 要匹配的变量名 */
	struct case_pattern *patterns;        /* 模式链表 */
};

/*============================================================================
 * 赋值节点结构体 - 表示变量赋值操作
 * 
 * 对应shell语法: VAR=value
 *============================================================================*/
struct assign_node {
	char *var_name;                       /* 变量名 */
	char *value;                          /* 要赋的值 */
};

/*============================================================================
 * 重定向信息结构体 - 表示I/O重定向操作
 * 
 * 用于存储输入/输出重定向的详细信息。
 * 支持 < (输入), > (输出覆盖), >> (输出追加)
 *============================================================================*/
struct redirect_info {
	int type;                             /* 重定向类型（TOKEN_REDIRECT_*） */
	char *filename;                       /* 目标文件名 */
	int fd;                               /* 文件描述符（0=stdin, 1=stdout, 2=stderr） */
	struct redirect_info *next;           /* 指向下一个重定向的指针（支持多重重定向） */
};

/*============================================================================
 * AST节点结构体 - 抽象语法树的主要节点结构
 * 
 * 这是AST的核心结构，使用联合体(union)来存储不同类型节点的数据。
 * 这样设计可以节省内存，因为每个节点只需要存储一种类型的数据。
 *============================================================================*/
struct ast_node {
	ast_node_type_t type;                 /* 节点类型 */
	union {
		struct cmd_node cmd;              /* 命令节点数据 */
		struct pipeline_node pipeline;    /* 管道节点数据 */
		struct if_node if_stmt;           /* if语句节点数据 */
		struct while_node while_loop;     /* while循环节点数据 */
		struct for_node for_loop;         /* for循环节点数据 */
		struct case_node case_stmt;       /* case语句节点数据 */
		struct assign_node assign;        /* 赋值节点数据 */
		struct ast_node *sequence[2];     /* 顺序执行节点数据（两个子节点） */
	} data;
	struct ast_node *next;                /* 指向下一个节点的指针（用于语句链表） */
};

/*============================================================================
 * 变量表条目结构体 - 哈希表中的单个变量条目
 * 
 * 存储一个shell变量的名称、值和导出状态。
 * 使用链地址法解决哈希冲突（next指针）。
 *============================================================================*/
struct var_entry {
	char name[MAX_VAR_NAME];              /* 变量名 */
	char value[MAX_VAR_VALUE];            /* 变量值 */
	int exported;                         /* 导出标志（1=环境变量，0=局部变量） */
	struct var_entry *next;               /* 哈希冲突链（链地址法） */
};

/*============================================================================
 * 变量表结构体 - 基于哈希表的变量存储
 * 
 * 使用哈希表来存储所有shell变量，提供O(1)的平均查找时间。
 * 使用链地址法处理哈希冲突。
 *============================================================================*/
struct var_table {
	struct var_entry *buckets[HASH_TABLE_SIZE];  /* 哈希桶数组 */
	int count;                                    /* 变量总数 */
};

/*============================================================================
 * 执行上下文结构体 - 命令执行时的环境信息
 * 
 * 包含命令执行所需的所有上下文信息，如变量表、退出码、
 * 当前目录等。在整个执行过程中传递这个上下文。
 *============================================================================*/
struct exec_context {
	struct var_table *vars;               /* 变量表指针 */
	int last_exit_code;                   /* 上一个命令的退出码（对应$?变量） */
	int should_exit;                      /* 退出标志（1=应该退出shell） */
	void *callback_data;                  /* 回调函数的用户数据 */
	char current_dir[MAX_PATH_LEN];       /* 当前工作目录 */
};

/*============================================================================
 * 内存池节点结构体 - 用于高效内存分配
 * 
 * 内存池中的每个节点记录一次分配的信息。
 * 所有分配会在池销毁时统一释放，减少内存碎片。
 *============================================================================*/
struct mem_pool_node {
	void *ptr;                            /* 分配的内存块指针 */
	size_t size;                          /* 分配的大小（字节） */
	struct mem_pool_node *next;           /* 指向下一个节点的指针 */
};

/*============================================================================
 * 内存池结构体 - 批量内存管理
 * 
 * 内存池通过批量管理内存分配来提高性能并减少碎片。
 * 所有通过池分配的内存会在池销毁时统一释放。
 *============================================================================*/
struct mem_pool {
	struct mem_pool_node *head;           /* 分配节点链表头 */
	size_t total_allocated;               /* 总分配字节数 */
	size_t block_count;                   /* 分配块数量 */
};

/*============================================================================
 * 命令映射条目结构体 - Unix命令到Windows命令的映射
 * 
 * 用于将Unix/Linux命令转换为Windows等效命令。
 * 例如: ls -> dir, rm -> del
 *============================================================================*/
struct cmd_mapping {
	const char *unix_cmd;                 /* Unix命令名 */
	const char *windows_cmd;              /* 对应的Windows命令名 */
};

#endif /* _SHELL_TYPES_H */

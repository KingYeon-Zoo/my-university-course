/******************************************************************************
* 文件名:     Hazard_Unit.v
* 描述:       冒险检测单元 (Hazard Detection Unit)
*             检测 Load-Use 数据冒险并生成流水线停顿信号
*
* Load-Use 冒险:
*   当前一条指令是 Load，且下一条指令需要使用 Load 的结果时，
*   由于 Load 数据在 MEM 阶段才能获得，无法通过前递解决，
*   必须停顿流水线一个周期
*
* 示例:
*   LW  x1, 0(x2)    // Load 指令，x1 在 MEM 阶段才有值
*   ADD x3, x1, x4   // 需要 x1，必须等待一个周期
*
* 停顿方法:(EX_Mem_r && ((RdAddr == Rs1Addr) || (RdAddr == Rs2Addr)))  EX 阶段是 Load 指令，且其 Rd 与 ID 阶段的 Rs1 或 Rs2 相同
*   1. IF_ID_w = 0   : 停止 IF/ID 寄存器更新，保持当前指令
*   2. ID_EX_Flush = 1: 在 ID/EX 之间插入气泡 (NOP)
*   3. PC 不更新     : 通过 PC_Adder 的 IF_ID_w 控制（控制的是pc adder）
******************************************************************************/

`include "SYSTEM_DEF.vh"

module Hazard_Unit(
    //=========================================================================
    // ID 阶段的源寄存器地址
    //=========================================================================
    input [`ADDR_WIDTH - 1:0] Rs1Addr,      // ID 阶段指令的 Rs1 地址
    input [`ADDR_WIDTH - 1:0] Rs2Addr,      // ID 阶段指令的 Rs2 地址
    
    //=========================================================================
    // EX 阶段的信息
    //=========================================================================
    input [`ADDR_WIDTH - 1:0] RdAddr,       // EX 阶段指令的 Rd 地址
    input EX_Mem_r,                         // EX 阶段是否是 Load 指令
    
    //=========================================================================
    // 输出控制信号
    //=========================================================================
    output reg IF_ID_w,                     // IF/ID 写使能 (0=停顿)
    output reg ID_EX_Flush_0                // ID/EX 冲刷信号 (1=插入气泡)
);

    // 初始值: 正常运行
    initial begin
        IF_ID_w = 1;
        ID_EX_Flush_0 = 0;
    end

    always @(*) begin
        //=====================================================================
        // Load-Use 冒险检测
        // 条件: EX 阶段是 Load 指令，且其 Rd 与 ID 阶段的 Rs1 或 Rs2 相同
        //=====================================================================
        if(EX_Mem_r && ((RdAddr == Rs1Addr) || (RdAddr == Rs2Addr))) begin
            // 检测到 Load-Use 冒险
            IF_ID_w = 1'b0;                 // 停顿 IF/ID (保持当前指令)
            ID_EX_Flush_0 = 1'b1;           // 冲刷 ID/EX (插入 NOP)
        end 
        else begin
            // 无冒险，正常运行
            IF_ID_w = 1'b1;                 // IF/ID 正常写入
            ID_EX_Flush_0 = 1'b0;           // 不冲刷
        end
    end

endmodule

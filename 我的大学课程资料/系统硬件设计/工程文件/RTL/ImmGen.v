/******************************************************************************
* 文件名:     ImmGen.v
* 描述:       立即数生成器 (Immediate Generator)
*             从 32 位指令中提取立即数并进行符号扩展到 32 位
*
* RISC-V 有 5 种立即数格式:
*
*   I 型: imm[11:0] = inst[31:20]
*         用于: ADDI, LW, JALR 等
*
*   S 型: imm[11:5] = inst[31:25], imm[4:0] = inst[11:7]
*         用于: SW, SH, SB
*
*   B 型: imm[12|10:5|4:1|11] = inst[31|30:25|11:8|7], imm[0]=0
*         用于: BEQ, BNE, BLT 等分支指令
*
*   U 型: imm[31:12] = inst[31:12], imm[11:0] = 0
*         用于: LUI, AUIPC
*
*   J 型: imm[20|10:1|11|19:12] = inst[31|30:21|20|19:12], imm[0]=0
*         用于: JAL
******************************************************************************/

`include "SYSTEM_DEF.vh"

module ImmGen(
    input [`INSTR_WIDTH - 1:0] Instr,       // 32 位指令
    input [2:0] Imm_Type,                   // 立即数类型选择
    output reg [`DATA_WIDTH - 1:0] Imm      // 输出: 符号扩展后的 32 位立即数
);
    
    always @(*) begin
        case (Imm_Type)
            //=================================================================
            // I 型: 12 位有符号立即数
            // 位域: inst[31:20]
            // 符号扩展: inst[31] 扩展到高 20 位
            //=================================================================
            `I_TYPE_IMM : Imm = {{20{Instr[31]}}, Instr[31:20]};
            
            //=================================================================
            // S 型: 12 位有符号立即数 (分散存储)
            // 位域: inst[31:25] | inst[11:7]
            // 符号扩展: inst[31] 扩展到高 20 位
            //=================================================================
            `S_TYPE_IMM : Imm = {{20{Instr[31]}}, Instr[31:25], Instr[11:7]};
            
            //=================================================================
            // B 型: 13 位有符号立即数 (最低位恒为 0)
            // 位域: inst[31] | inst[7] | inst[30:25] | inst[11:8] | 0
            // 用于分支，偏移量必须是 2 的倍数
            //=================================================================
            `B_TYPE_IMM : Imm = {{19{Instr[31]}}, Instr[31], Instr[7], 
                                 Instr[30:25], Instr[11:8], 1'b0};
            
            //=================================================================
            // U 型: 20 位高位立即数
            // 位域: inst[31:12] 放在结果的高 20 位
            // 低 12 位填充 0
            //=================================================================
            `U_TYPE_IMM : Imm = {Instr[31:12], 12'b0};
            
            //=================================================================
            // J 型: 21 位有符号立即数 (最低位恒为 0)
            // 位域: inst[31] | inst[19:12] | inst[20] | inst[30:21] | 0
            // 用于 JAL，偏移量必须是 2 的倍数
            //=================================================================
            `J_TYPE_IMM : Imm = {{11{Instr[31]}}, Instr[31], Instr[19:12], 
                                 Instr[20], Instr[30:21], 1'b0};
            
            default : Imm = 0;
        endcase
    end

endmodule

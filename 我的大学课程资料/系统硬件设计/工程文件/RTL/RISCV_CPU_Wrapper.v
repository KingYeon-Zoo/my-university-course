/******************************************************************************
* 文件名:     RISCV_CPU_Wrapper.v
* 项目:       五级流水线 RISC-V CPU 设计 - FPGA上板验证包装模块
* 描述:       该模块在CPU核心外部添加硬件接口，用于FPGA开发板验证
*             包含LED指示灯、七段数码管显示、调试输出等功能
*
* 使用场景:
*   - FPGA上板验证: 使用本模块作为顶层
*   - 仿真验证: 使用 RISCV_CPU.v 作为顶层
*
* 硬件平台:   EGO1开发板 (Xilinx Artix-7 XC7A35T-CSG324-1)
*
* 接口说明:
*   输入:
*     - sys_clk:    系统时钟 (100MHz, 来自晶振)
*     - aresetn:    异步复位 (低电平有效, 来自复位按钮)
*   
*   输出:
*     - leds[15:0]: 16个LED指示灯
*                   - leds[7:0]:  显示寄存器x1的低8位
*                   - leds[15:8]: 显示PC的低8位
*     - seg[7:0]:   第一组七段数码管段选信号 (共阳极)
*     - an[7:0]:    第一组七段数码管位选信号
*     - seg1[7:0]:  第二组七段数码管段选信号
*     - debug_pc[31:0]: PC调试输出 (连接到J5扩展IO，可用逻辑分析仪观测)
*
* 数码管显示策略:
*   - 第一组数码管(seg, an): 显示寄存器x2的值 (32位十六进制)
*   - 第二组数码管(seg1):    使用相同的段选信号显示x2的高16位
*
* 创建时间:   2025-12-27
******************************************************************************/

`include "SYSTEM_DEF.vh"

module RISCV_CPU_Wrapper(
    input sys_clk,                      // 系统时钟 (100MHz)
    input aresetn,                      // 异步复位 (低电平有效)
    
    // FPGA板载硬件接口
    output [15:0] leds,                 // 16个LED指示灯
    output [7:0] seg,                   // 第一组七段数码管段选
    output [7:0] an,                    // 第一组七段数码管位选
    output [7:0] seg1,                  // 第二组七段数码管段选
    output [31:0] debug_pc              // PC调试输出
);

    //=========================================================================
    // 内部信号声明
    //=========================================================================
    
    // 寄存器堆读取信号（用于LED和数码管显示）
    wire [31:0] x1_value;               // 读取x1寄存器的值 (用于LED显示)
    wire [31:0] x2_value;               // 读取x2寄存器的值 (用于数码管显示)
    wire [31:0] current_pc;             // 当前PC值
    
    // 时钟和复位信号（可添加PLL或时钟管理，当前直连）
    wire cpu_clk;
    wire cpu_resetn;
    
    assign cpu_clk = sys_clk;           // 直接使用100MHz时钟
    assign cpu_resetn = aresetn;        // 直接使用复位信号
    
    //=========================================================================
    // LED指示灯分配
    //=========================================================================
    // LED[7:0]:   显示x1寄存器低8位 (可观察程序运行状态)
    // LED[15:8]:  显示PC的低8位 (可观察程序执行进度)
    //=========================================================================
    assign leds[7:0] = x1_value[7:0];
    assign leds[15:8] = current_pc[7:0];
    
    //=========================================================================
    // 调试输出
    //=========================================================================
    assign debug_pc = current_pc;      // 将PC输出到J5扩展IO
    
    //=========================================================================
    // 第二组数码管段选信号（复用第一组的段选）
    //=========================================================================
    assign seg1 = seg;                  // 两组数码管共用段选信号
    
    //=========================================================================
    // CPU核心实例化
    //=========================================================================
    // 注意: 必须在 SYSTEM_DEF.vh 中定义 FPGA_BOARD 宏才能启用调试接口
    
    RISCV_CPU cpu_core (
        .aclk(cpu_clk),
        .aresetn(cpu_resetn),
        .Debug_PC(current_pc),          // PC调试输出
        .Debug_Reg_Addr1(5'd1),         // 读x1寄存器
        .Debug_Reg_Data1(x1_value),
        .Debug_Reg_Addr2(5'd2),         // 读x2寄存器
        .Debug_Reg_Data2(x2_value)
    );
    
    //=========================================================================
    // 七段数码管驱动模块实例化
    //=========================================================================
    // 显示x2寄存器的值（32位，8个十六进制数字）
    
    seven_seg_driver seg_driver (
        .clk(cpu_clk),
        .rst_n(cpu_resetn),
        .data(x2_value),                // 显示x2寄存器
        .seg(seg),                      // 段选输出
        .an(an)                         // 位选输出
    );

endmodule


/******************************************************************************
* 使用说明:
*
* 1. 仿真模式:
*    - 使用 RISCV_CPU.v 作为顶层模块
*    - 在testbench中实例化 RISCV_CPU
*
* 2. 上板验证模式:
*    - 使用 RISCV_CPU_Wrapper.v 作为顶层模块
*    - 在Vivado中将 RISCV_CPU_Wrapper 设置为顶层

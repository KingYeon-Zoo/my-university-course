/******************************************************************************
* 文件名:     BPU.v
* 描述:       分支处理单元 (Branch Processing Unit)
*             在 EX 阶段计算分支目标地址，并判断分支条件是否成立
*
* 功能:
*   1. 计算分支目标地址: PC + Imm
*   2. 根据 ALU 结果和 funct3 判断分支是否跳转
*
* 分支条件 (由 funct3 决定):
*   000 - BEQ  : 相等则跳转 (Zero_Flag = 1)
*   001 - BNE  : 不等则跳转 (Zero_Flag = 0)
*   100 - BLT  : 有符号小于则跳转 (ALU_Result[0] = 1, SLT 结果)
*   101 - BGE  : 有符号大于等于则跳转 (ALU_Result[0] = 1, GE 结果)
*   110 - BLTU : 无符号小于则跳转 (ALU_Result[0] = 1, SLTU 结果)
*   111 - BGEU : 无符号大于等于则跳转 (ALU_Result[0] = 1, GEU 结果)
******************************************************************************/

`include "SYSTEM_DEF.vh"

module BPU (
    //=========================================================================
    // 来自 ALU 的比较结果
    //=========================================================================
    input ALU_Result0,                      // ALU 结果的最低位 (比较结果)
    input Zero_Flag,                        // 零标志 (用于 BEQ/BNE)
    
    //=========================================================================
    // 指令信息
    //=========================================================================
    input [2:0] Funct3,                     // funct3 决定分支类型
    input EX_Branch,                        // 是否是分支指令
    
    //=========================================================================
    // 地址计算
    //=========================================================================
    input [`PC_WIDTH-1:0] EX_PC,            // 当前 PC
    input [`DATA_WIDTH-1:0] EX_Imm,         // 分支偏移量
    
    //=========================================================================
    // 输出
    //=========================================================================
    output [`PC_WIDTH-1:0] PC_Plus_Imm,     // 分支目标地址 = PC + Imm
    output Branch_Taken                     // 分支是否跳转
);

    reg Taken;
    
    // 计算分支目标地址
    assign PC_Plus_Imm = EX_PC + EX_Imm;
    
    // 最终跳转信号: 是分支指令 AND 条件成立
    assign Branch_Taken = Taken && EX_Branch;

    //=========================================================================
    // 分支条件判断
    //=========================================================================
    always @(*) begin
        case(Funct3)
            //=================================================================
            // BEQ: 相等则跳转
            // 条件: rs1 == rs2 -> ALU 做减法，结果为 0
            //=================================================================
            3'b000: Taken = Zero_Flag;
            
            //=================================================================
            // BNE: 不等则跳转
            // 条件: rs1 != rs2 -> ALU 做减法，结果不为 0
            //=================================================================
            3'b001: Taken = !Zero_Flag;
            
            //=================================================================
            // BLT: 有符号小于则跳转
            // 条件: rs1 < rs2 (有符号) -> ALU 做 SLT，结果为 1
            //=================================================================
            3'b100: Taken = ALU_Result0;
            
            //=================================================================
            // BGE: 有符号大于等于则跳转
            // 条件: rs1 >= rs2 (有符号) -> ALU 做 GE，结果为 1
            //=================================================================
            3'b101: Taken = ALU_Result0;
            
            //=================================================================
            // BLTU: 无符号小于则跳转
            // 条件: rs1 < rs2 (无符号) -> ALU 做 SLTU，结果为 1
            //=================================================================
            3'b110: Taken = ALU_Result0;
            
            //=================================================================
            // BGEU: 无符号大于等于则跳转
            // 条件: rs1 >= rs2 (无符号) -> ALU 做 GEU，结果为 1
            //=================================================================
            3'b111: Taken = ALU_Result0;
            
            default: Taken = 0;    
        endcase
    end

endmodule

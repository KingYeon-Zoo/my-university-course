/******************************************************************************
* 文件名:     BTB.v
* 描述:       分支目标缓冲 (Branch Target Buffer)
*             缓存分支指令的跳转目标地址，用于分支预测
*
* 工作原理:
*   当分支被预测为跳转时，需要知道跳转到哪里
*   BTB 存储了之前执行过的分支指令的目标地址
*   通过 PC 的低位索引 BTB，获取之前记录的跳转目标
*
* 结构:
*   - BTB 数组: 存储跳转目标地址
*   - Valid 数组: 标记该项是否有效
*
* 使用时机:
*   IF 阶段: 用 PC 索引 BTB，如果 Valid 有效则输出目标地址
*   EX 阶段: 如果分支实际跳转，更新 BTB 中的目标地址
******************************************************************************/

`include "SYSTEM_DEF.vh"

module BTB(
    input clk,                              // 系统时钟
    input rst_n,                            // 异步复位 (低电平有效)
    
    //=========================================================================
    // IF 阶段: 查询
    //=========================================================================
    input [`BTB_PC_WIDTH - 1:0] PC_Tag,     // 当前 PC 的低位 (用于索引)
    output [`PC_WIDTH - 1:0] BTB_PC,        // 输出: 预测的跳转目标地址
    output BTB_Valid,                       // 输出: BTB 项是否有效
    
    //=========================================================================
    // EX 阶段: 更新
    //=========================================================================
    input [`BTB_PC_WIDTH - 1:0] EX_PC_Tag,  // EX 阶段 PC 的低位 (用于更新)
    input [`PC_WIDTH - 1:0] Branch_PC,      // 实际跳转目标地址
    input Branch_Taken                      // 实际分支结果
);

    integer i;
    
    // BTB 存储结构
    reg [`PC_WIDTH - 1:0] BTB [0:`BTB_SIZE-1];  // 跳转目标地址数组
    reg Valid [0:`BTB_SIZE-1];                   // 有效位数组

    //=========================================================================
    // 查询逻辑: 根据 PC 索引返回目标地址和有效位
    //=========================================================================
    assign BTB_PC = BTB[PC_Tag];            // 预测的跳转目标
    assign BTB_Valid = Valid[PC_Tag];       // 是否命中

    //=========================================================================
    // 更新逻辑: 分支实际跳转时更新 BTB
    //=========================================================================
    always @(posedge clk or negedge rst_n) begin
        if(!rst_n) begin
            // 复位: 清空所有 BTB 项
            for(i = 0; i < `BTB_SIZE; i = i + 1) begin
                BTB[i] <= 0;
                Valid[i] <= 0;
            end
        end
        else begin
            if(Branch_Taken) begin
                // 分支实际跳转: 记录跳转目标地址，此时是在EX阶段，所以使用EX_PC_Tag
                BTB[EX_PC_Tag] <= Branch_PC;
                Valid[EX_PC_Tag] <= 1;
            end
            else;
            // 注意: 不跳转时不清除 BTB 项，保留历史记录
        end
    end
endmodule

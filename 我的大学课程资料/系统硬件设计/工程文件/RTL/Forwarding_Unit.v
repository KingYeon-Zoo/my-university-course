/******************************************************************************
* 文件名:     Forwarding_Unit.v
* 描述:       数据前递单元 (Data Forwarding Unit)
*             检测数据冒险并生成前递控制信号，将后续阶段的数据直接旁路到 EX 阶段
*
* 数据冒险场景:
*   EX 阶段的指令需要使用前面指令的结果，但前面指令尚未写回寄存器堆
*
* 前递来源优先级:
*   1. MEM 阶段 (EX/MEM 寄存器) - 最新的数据，优先级最高
*   2. WB 阶段 (MEM/WB 寄存器) - 次新的数据
*   3. 寄存器堆 - 正常读取
*
* Forward 编码:
*   00 - 不前递，使用 ID/EX 寄存器中的数据
*   01 - 从 WB 阶段前递 (WB_Data)
*   10 - 从 MEM 阶段前递 (MEM_ALU_Result)
******************************************************************************/

`include "SYSTEM_DEF.vh"

module Forwarding_Unit(
    //=========================================================================
    // MEM 阶段信息 (检测是否需要从 MEM 前递)
    //=========================================================================
    input [`ADDR_WIDTH - 1:0] MEM_Rd_Addr,  // MEM 阶段的目标寄存器地址
    input MEM_Reg_w,                        // MEM 阶段是否写寄存器
    
    //=========================================================================
    // WB 阶段信息 (检测是否需要从 WB 前递)
    //=========================================================================
    input [`ADDR_WIDTH - 1:0] WB_Rd_Addr,   // WB 阶段的目标寄存器地址
    input WB_Reg_w,                         // WB 阶段是否写寄存器
    
    //=========================================================================
    // EX 阶段信息 (当前需要数据的指令)
    //=========================================================================
    input [`ADDR_WIDTH - 1:0] EX_Rs1_Addr,  // EX 阶段的 Rs1 地址
    input [`ADDR_WIDTH - 1:0] EX_Rs2_Addr,  // EX 阶段的 Rs2 地址
    
    //=========================================================================
    // 前递控制信号输出
    //=========================================================================
    output reg [1:0] Forward_A,             // Rs1 的前递选择
    output reg [1:0] Forward_B              // Rs2 的前递选择
);

    // 检测条件: 写使能有效且目标不是 x0
    wire load_EX_MEM = (MEM_Reg_w && MEM_Rd_Addr != 0);  // MEM 阶段有有效写入
    wire load_MEM_WB = (WB_Reg_w && WB_Rd_Addr != 0);    // WB 阶段有有效写入

    always @(*) begin
        //=====================================================================
        // Rs1 (Forward_A) 前递判断
        // 优先级: MEM 阶段 > WB 阶段 > 寄存器堆
        //=====================================================================
        if(load_EX_MEM && (MEM_Rd_Addr == EX_Rs1_Addr)) 
            Forward_A = 2'b10;              // 从 MEM 阶段前递 ALU_Result
        else if(load_MEM_WB && (WB_Rd_Addr == EX_Rs1_Addr)) 
            Forward_A = 2'b01;              // 从 WB 阶段前递 WB_Data
        else 
            Forward_A = 2'b00;              // 不前递，使用寄存器堆数据

        //=====================================================================
        // Rs2 (Forward_B) 前递判断
        // 优先级: MEM 阶段 > WB 阶段 > 寄存器堆
        //=====================================================================
        if(load_EX_MEM && (MEM_Rd_Addr == EX_Rs2_Addr)) 
            Forward_B = 2'b10;              // 从 MEM 阶段前递 ALU_Result
        else if(load_MEM_WB && (WB_Rd_Addr == EX_Rs2_Addr)) 
            Forward_B = 2'b01;              // 从 WB 阶段前递 WB_Data
        else 
            Forward_B = 2'b00;              // 不前递，使用寄存器堆数据
    end

endmodule

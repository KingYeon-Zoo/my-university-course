/******************************************************************************
* 文件名:     LDU.v
* 描述:       加载数据单元 (Load Data Unit)
*             对从数据存储器读取的数据进行符号扩展或零扩展
*
* 支持的 Load 指令 (由 funct3 决定):
*   000 - LB  : 加载字节 (8位有符号扩展到32位)
*   001 - LH  : 加载半字 (16位有符号扩展到32位)
*   010 - LW  : 加载字 (32位，无需扩展)
*   100 - LBU : 加载无符号字节 (8位零扩展到32位)
*   101 - LHU : 加载无符号半字 (16位零扩展到32位)
******************************************************************************/

`include "SYSTEM_DEF.vh"

module LDU(
    input [2:0] MEM_Funct3,                 // funct3 决定加载类型
    input [`DATA_WIDTH - 1:0] Mem_R_Data,   // 从数据存储器读取的原始数据
    output reg [`DATA_WIDTH - 1:0] LDU_Result  // 输出: 扩展后的数据
);

    always @(*) begin
        case(MEM_Funct3)
            //=================================================================
            // 有符号扩展: 将符号位复制到高位
            //=================================================================
            3'b000 : begin
                // LB: 加载字节 (符号扩展)
                // 将 bit[7] 符号位扩展到高 24 位
                LDU_Result = {{24{Mem_R_Data[7]}}, Mem_R_Data[7:0]};
            end
            
            3'b001 : begin
                // LH: 加载半字 (符号扩展)
                // 将 bit[15] 符号位扩展到高 16 位
                LDU_Result = {{16{Mem_R_Data[15]}}, Mem_R_Data[15:0]};
            end
            
            //=================================================================
            // 无扩展: 直接使用 32 位数据
            //=================================================================
            3'b010 : begin
                // LW: 加载字 (无需扩展)
                LDU_Result = Mem_R_Data;
            end
            
            //=================================================================
            // 零扩展: 高位填充 0
            //=================================================================
            3'b100 : begin
                // LBU: 加载无符号字节 (零扩展)
                LDU_Result = {24'b0, Mem_R_Data[7:0]};
            end
            
            3'b101 : begin
                // LHU: 加载无符号半字 (零扩展)
                LDU_Result = {16'b0, Mem_R_Data[15:0]};
            end
            
            default : LDU_Result = Mem_R_Data;
        endcase
    end
endmodule

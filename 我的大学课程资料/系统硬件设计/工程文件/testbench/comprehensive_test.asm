// =============================================================================

// =============================================================================
// 第一部分: 基础初始化 (基于学号)
// =============================================================================
ADDI x1, x0, 20          // x1 = 20
ADDI x2, x0, 23          // x2 = 23
ADDI x3, x0, 12          // x3 = 12
ADDI x5, x0, 90          // x5 = 90

// =============================================================================
// 第二部分: 基础运算测试 (各选一条代表)
// =============================================================================
ADD x7, x1, x2           // R型: x7 = 43
ANDI x8, x5, 15          // I型: x8 = 10
SLLI x9, x2, 2           // 移位: x9 = 92
MUL x10, x2, x3          // M扩展: x10 = 276
DIV x11, x5, x2          // 除法: x11 = 3

// =============================================================================
// 第三部分: 访存指令测试 (只验证基本功能)
// =============================================================================
ADDI x12, x0, 0          // 基址
SW x1, 0(x12)            // 存一个
LW x13, 0(x12)           // 读一个: x13 = 20

// =============================================================================
// ★ 第四部分: 数据前递测试 (展示关键特性)
// =============================================================================
ADD x14, x1, x2          // x14 = 43
ADD x15, x14, x3         // x15 = 55 ← EX-EX前递 (Forward_A=10)
ADD x16, x15, x1         // x16 = 75 ← EX-EX前递 (Forward_A=10)

// =============================================================================
// ★ 第五部分: Load-Use 冒险 (展示流水线停顿)
// =============================================================================
LW x17, 0(x12)           // x17 = Mem[0] = 20
ADD x18, x17, x2         // ← Load-Use停顿! IF_ID_w=0, 插入气泡

// =============================================================================
// ★★★ 第六部分: 分支预测训练 (重点展示)
// =============================================================================
// 循环10次，观察BHT从 00→01→10→11 的训练过程
ADDI x19, x0, 0          // 计数器
ADDI x20, x0, 10         // 循环10次

// 循环体 (BHT训练的关键)
ADDI x19, x19, 1         // x19++
BLT x19, x20, -4         // 跳转 (前2次预测错误，后面预测正确)
                         // 观察: Predict_Taken, Branch_Taken, IF_ID_Flush

// =============================================================================
// ★ 第七部分: 预测失败场景
// =============================================================================
ADDI x21, x0, 0
ADDI x22, x0, 5

// 训练阶段 (5次跳转)
ADDI x21, x21, 1
BNE x21, x22, -4         // 跳转5次，训练BHT为11

// 预测失败 (突然不跳转)
BNE x21, x22, 8          // x21=5, x22=5, 不跳转但BHT预测跳转!
ADDI x23, x0, 99         // 这条会执行 (预测错误恢复)

// =============================================================================
// ★ 第八部分: 嵌套循环 (展示分支+前递组合)
// =============================================================================
ADDI x24, x0, 0          // 外循环
ADDI x25, x0, 3          // 外循环3次
ADDI x30, x0, 0          // 累加器

// 外循环体
ADDI x26, x0, 0          // 内循环
ADDI x27, x0, 4          // 内循环4次

// 内循环体
ADDI x30, x30, 1         // 累加 (数据前递)
ADDI x26, x26, 1         // 内循环++
BLT x26, x27, -8         // 内循环条件

ADDI x24, x24, 1         // 外循环++
BLT x24, x25, -20        // 外循环条件
                         // x30 = 12 (3×4)

// =============================================================================
// 第九部分: 分支类型测试 (各一条)
// =============================================================================
ADDI x28, x0, 10
ADDI x29, x0, 10

BEQ x28, x29, 4          // 相等跳转
ADDI x31, x0, 1
BNE x28, x29, 4          // 不等不跳转
ADDI x31, x0, 2

// =============================================================================
// 第十部分: 跳转指令
// =============================================================================
JAL x7, 8                // JAL跳转，保存返回地址
ADDI x8, x0, 100         // 被冲刷
ADDI x8, x0, 7           // 执行: x8 = 7

LUI x9, 0x12345          // LUI: x9 = 0x12345000
AUIPC x10, 0x1000        // AUIPC: x10 = PC + 0x1000000

// =============================================================================
// 第十一部分: 完成标记
// =============================================================================
LUI x30, 0x20232         // 学号高位
ADDI x30, x30, 290       // x30 = 2023212290
LUI x31, 0xDEADB         // 完成标记
ADDI x31, x31, -273      // x31 = 0xDEADBEEF

// =============================================================================
// 无限循环
// =============================================================================
JAL x0, 0                // 永远循环

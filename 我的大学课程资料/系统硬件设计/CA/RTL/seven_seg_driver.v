/******************************************************************************
* 文件名: seven_seg_driver.v
* 功能:   8 位七段数码管动态扫描驱动
* 板卡:   EGO1 (Artix-7 XC7A35T)
*
* 显示规则:
*   - 输入 32-bit data
*   - 每 4 bit 显示为 1 个 16 进制数
*   - 共 8 位数码管，显示 data[31:0]
*
* 硬件假设（EGo1 实际）:
*   - 共阴极数码管
*   - 段选 seg：高电平点亮
*   - 位选 an ：高电平选中
******************************************************************************/

module seven_seg_driver (
    input  wire        clk,        // 系统时钟（100MHz）
    input  wire        rst_n,      // 异步复位，低有效
    input  wire [31:0] data,       // 要显示的数据（如 regs）
    output reg  [7:0]  seg,        // 段选 a~g,dp（高有效）
    output reg  [7:0]  an          // 位选 DIG0~DIG7（高有效）
);

    //======================================================================
    // 0. 内部段码（逻辑意义：1 = 点亮该段）
    //======================================================================
    reg [7:0] seg_raw;

    //======================================================================
    // 1. 扫描时钟分频
    //======================================================================
    // 100MHz / 100_000 ≈ 1kHz 扫描频率
    reg [16:0] div_cnt;
    reg        scan_clk;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            div_cnt  <= 0;
            scan_clk <= 0;
        end else if (div_cnt == 17'd100_000 - 1) begin
            div_cnt  <= 0;
            scan_clk <= ~scan_clk;
        end else begin
            div_cnt <= div_cnt + 1;
        end
    end

    //======================================================================
    // 2. 位扫描计数器（0~7）
    //======================================================================
    reg [2:0] scan_idx;

    always @(posedge scan_clk or negedge rst_n) begin
        if (!rst_n)
            scan_idx <= 3'd0;
        else
            scan_idx <= scan_idx + 3'd1;
    end

    //======================================================================
    // 3. 位选控制（高有效，共阴极）
    //======================================================================
    always @(*) begin
        an = 8'b0000_0000;      // 默认全不选
        an[scan_idx] = 1'b1;   // 当前位选中
    end

    //======================================================================
    // 4. 取当前 4-bit 数据
    //======================================================================
    reg [3:0] hex;

    always @(*) begin
        case (scan_idx)
            3'd0: hex = data[3:0];
            3'd1: hex = data[7:4];
            3'd2: hex = data[11:8];
            3'd3: hex = data[15:12];
            3'd4: hex = data[19:16];
            3'd5: hex = data[23:20];
            3'd6: hex = data[27:24];
            3'd7: hex = data[31:28];
            default: hex = 4'h0;
        endcase
    end

    //======================================================================
    // 5. 7 段译码（逻辑层：1 = 点亮该段）
    // seg_raw = {dp, g, f, e, d, c, b, a}
    //======================================================================
    always @(*) begin
        case (hex)
            4'h0: seg_raw = 8'b0011_1111;
            4'h1: seg_raw = 8'b0000_0110;
            4'h2: seg_raw = 8'b0101_1011;
            4'h3: seg_raw = 8'b0100_1111;
            4'h4: seg_raw = 8'b0110_0110;
            4'h5: seg_raw = 8'b0110_1101;
            4'h6: seg_raw = 8'b0111_1101;
            4'h7: seg_raw = 8'b0000_0111;
            4'h8: seg_raw = 8'b0111_1111;
            4'h9: seg_raw = 8'b0110_1111;
            4'hA: seg_raw = 8'b0111_0111;
            4'hB: seg_raw = 8'b0111_1100;
            4'hC: seg_raw = 8'b0011_1001;
            4'hD: seg_raw = 8'b0101_1110;
            4'hE: seg_raw = 8'b0111_1001;
            4'hF: seg_raw = 8'b0111_0001;
            default: seg_raw = 8'b0000_0000;
        endcase
    end

    //======================================================================
    // 6. 物理输出（EGo1：共阴极，高电平点亮）
    //======================================================================
    always @(*) begin
        seg = seg_raw;
    end

endmodule

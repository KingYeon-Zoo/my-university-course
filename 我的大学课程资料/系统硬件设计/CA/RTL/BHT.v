/******************************************************************************
* 文件名:     BHT.v
* 描述:       分支历史表 (Branch History Table)
*             使用 2-bit 饱和计数器进行动态分支预测
*
* 工作原理:
*   每个 PC 地址对应一个 2-bit 计数器，记录该地址分支的历史行为
*   计数器值越大，越倾向于预测跳转
*
* 2-bit 饱和计数器状态:
*   00 - 强不跳转 (Strongly Not Taken)
*   01 - 弱不跳转 (Weakly Not Taken)
*   10 - 弱跳转   (Weakly Taken)
*   11 - 强跳转   (Strongly Taken)
*
* 预测规则:
*   state[1] = 0 -> 预测不跳转
*   state[1] = 1 -> 预测跳转
*
* 更新规则:
*   实际跳转: 计数器 +1 (最大 11)
*   实际不跳转: 计数器 -1 (最小 00)
******************************************************************************/

`include "SYSTEM_DEF.vh"

module BHT (
    input clk,                              // 系统时钟
    input rst_n,                            // 异步复位 (低电平有效)
    
    //=========================================================================
    // IF 阶段: 预测
    //=========================================================================
    input [`BHT_PC_WIDTH - 1:0] PC_Tag,     // 当前 PC 的低位 (用于索引)
    output Predict,                         // 预测结果 (1=跳转, 0=不跳转)
    
    //=========================================================================
    // EX 阶段: 更新
    //=========================================================================
    input Branch_Taken,                     // 实际分支结果 (1=跳转)
    input [`BHT_PC_WIDTH - 1:0] EX_PC_Tag   // EX 阶段 PC 的低位 (用于更新)
);

    // 64 项 2-bit 饱和计数器
    reg [1:0] state [0:`BHT_SIZE-1];
    integer i;

    //=========================================================================
    // 预测逻辑: 查看计数器高位
    // state[1] = 1 表示处于 "跳转" 状态 (10 或 11)
    //=========================================================================
    assign Predict = state[PC_Tag][1]; 

    //=========================================================================
    // 更新逻辑: 根据实际分支结果更新计数器
    //=========================================================================
    always @(posedge clk or negedge rst_n) begin
        if(!rst_n) begin
            // 复位: 所有计数器初始化为 00 (强不跳转)
            for(i = 0; i < `BHT_SIZE; i = i + 1) 
                state[i] <= 2'b00;
        end
        else begin
            if(Branch_Taken) begin
                // 实际跳转: 计数器 +1 (饱和在 11)
                state[EX_PC_Tag] <= (state[EX_PC_Tag] == 2'b11)? 2'b11 : state[EX_PC_Tag] + 1;
            end
            else begin
                // 实际不跳转: 计数器 -1 (饱和在 00)
                state[EX_PC_Tag] <= (state[EX_PC_Tag] == 2'b00)? 2'b00 : state[EX_PC_Tag] - 1;
            end
        end
    end

endmodule

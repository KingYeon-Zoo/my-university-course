def transform_personal(text: str) -> str:
    text = text.replace("\r\n", "\n")
    lines = []
    section_map: dict[str, str] = {}
    for raw in text.splitlines():
        if raw.startswith("# "):
            continue
        match_section = re.match(r"^##\s+(\d+)\.\s*(.+)$", raw)
        if match_section:
            number, title = match_section.groups()
            section_map[number] = title
            lines.append(f"## A.{number} {title}")
            continue
        match_subsection = re.match(r"^###\s+(\d+)\.(\d+)\s+(.+)$", raw)
        if match_subsection:
            major, minor, title = match_subsection.groups()
            lines.append(f"### A.{major}.{minor} {title}")
            continue
        raw = re.sub(r"^(\s*)（(\d+)）\s*", r"\1\2. ", raw)
        raw = re.sub(r"^(\s*)(\d+)、\s*", r"\1\2. ", raw)
        lines.append(raw)
    return "\n".join(lines).strip()


def normalize_markdown(text: str) -> str:
    text = re.sub(r"(?m)^---\s*$", "", text)
    text = re.sub(r"(?m)^(\s*)[-+*]\s+", r"\g<1>1. ", text)
    text = re.sub(r"(?m)^(\s*)[•▪◦·]\s*", r"\g<1>1. ", text)
    text = re.sub(r"\n{4,}", "\n\n\n", text)
    return text.strip() + "\n"


